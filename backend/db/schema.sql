-- Script de creación de la base (PostgreSQL / Neon).
--
-- Hibernate corre con ddl-auto=validate: NO crea tablas, solo verifica
-- que estas coincidan con las entidades. Los datos iniciales (tipos,
-- servicios, ciudades y alojamientos de ejemplo) los carga el backend
-- al arrancar si las tablas están vacías (DatosIniciales / DatosHospedajes).
--
-- Usa CREATE TABLE IF NOT EXISTS: se puede correr sobre la base de Neon
-- que ya tiene datos sin borrar nada, y en una base vacía crea todo.
-- Se corre desde el SQL Editor de Neon (o con psql).
-- =====================================================================

-- ── Catálogos ─────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS pais (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS ciudad (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre  VARCHAR(100) NOT NULL,
  id_pais BIGINT       NOT NULL REFERENCES pais (id)
);

CREATE TABLE IF NOT EXISTS tipo_hospedaje (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS servicio (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS tipo_usuario (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE
);

-- ── Usuarios ──────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS usuario (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username           VARCHAR(50)  NOT NULL UNIQUE,
  password           VARCHAR(100) NOT NULL,          -- hash BCrypt, nunca el texto
  email              VARCHAR(150) NOT NULL UNIQUE,
  nombre             VARCHAR(100) NOT NULL,
  apellido           VARCHAR(100) NOT NULL,
  fecha_nacimiento   DATE,
  fecha_creacion     TIMESTAMP(6) NOT NULL,
  fecha_modificacion TIMESTAMP(6),
  id_tipo_usuario    BIGINT       NOT NULL REFERENCES tipo_usuario (id)
);

-- ── Alojamientos ──────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS hospedaje (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre             VARCHAR(150)     NOT NULL,
  descripcion        VARCHAR(2000),
  precio_por_noche   NUMERIC(12,2)    NOT NULL,
  capacidad          INTEGER          NOT NULL,
  imagen             VARCHAR(500),                   -- foto de portada
  calificacion       DOUBLE PRECISION,
  resenas            INTEGER,
  habitaciones       INTEGER,
  camas              INTEGER,
  banos              INTEGER,
  destacado          VARCHAR(20),
  fecha_creacion     TIMESTAMP(6)     NOT NULL,
  fecha_modificacion TIMESTAMP(6),
  id_ciudad          BIGINT           NOT NULL REFERENCES ciudad (id),
  id_tipo_hospedaje  BIGINT           NOT NULL REFERENCES tipo_hospedaje (id),
  id_anfitrion       BIGINT           NOT NULL REFERENCES usuario (id)
);

-- Galería de fotos (Hospedaje.imagenes)
CREATE TABLE IF NOT EXISTS hospedaje_imagen (
  id_hospedaje BIGINT  NOT NULL REFERENCES hospedaje (id),
  orden        INTEGER NOT NULL,
  url          VARCHAR(500),
  PRIMARY KEY (id_hospedaje, orden)
);

-- Servicios de cada alojamiento (Hospedaje.servicios)
CREATE TABLE IF NOT EXISTS servicio_hospedaje (
  id_hospedaje BIGINT NOT NULL REFERENCES hospedaje (id),
  id_servicio  BIGINT NOT NULL REFERENCES servicio (id)
);

-- ── Reservas ──────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS reserva (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_hospedaje       BIGINT        NOT NULL REFERENCES hospedaje (id),
  id_usuario         BIGINT        NOT NULL REFERENCES usuario (id),   -- el huésped
  fecha_check_in     DATE          NOT NULL,
  fecha_check_out    DATE          NOT NULL,
  cant_adultos       INTEGER       NOT NULL,
  cant_ninos         INTEGER       NOT NULL,
  cant_bebes         INTEGER       NOT NULL,
  cant_mascotas      INTEGER       NOT NULL,
  importe_total      NUMERIC(12,2) NOT NULL,
  estado             VARCHAR(20)   NOT NULL CHECK (estado IN ('ACTIVA', 'CANCELADA')),
  fecha_creacion     TIMESTAMP(6)  NOT NULL,
  fecha_modificacion TIMESTAMP(6),
  CHECK (fecha_check_out > fecha_check_in)
);
