-- Script de la base (PostgreSQL / Neon) - PP1 2026 Grupo 1
-- Usa IF NOT EXISTS, asi que se puede correr sobre la base que ya tiene datos.
-- Los datos de ejemplo los carga el backend al arrancar.

-- catálogos
CREATE TABLE IF NOT EXISTS pais (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS ciudad (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre  VARCHAR(100) NOT NULL,
  id_pais BIGINT       NOT NULL REFERENCES pais (id)
);

CREATE TABLE IF NOT EXISTS tipo_hospedaje (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS servicio (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS tipo_usuario (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE
);

-- usuarios
CREATE TABLE IF NOT EXISTS usuario (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username           VARCHAR(50)  NOT NULL UNIQUE,
  password           VARCHAR(100) NOT NULL,          -- hash
  email              VARCHAR(150) NOT NULL UNIQUE,
  nombre             VARCHAR(100) NOT NULL,
  apellido           VARCHAR(100) NOT NULL,
  fecha_nacimiento   DATE,
  fecha_creacion     TIMESTAMP(6) NOT NULL,
  fecha_modificacion TIMESTAMP(6),
  id_tipo_usuario    BIGINT       NOT NULL REFERENCES tipo_usuario (id)
);

-- confirmacion de correo (las cuentas que ya existen quedan como verificadas)
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS email_verificado BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS token_verificacion VARCHAR(100);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS token_verificacion_vence TIMESTAMP(6);

-- alojamientos
CREATE TABLE IF NOT EXISTS hospedaje (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre             VARCHAR(150)     NOT NULL,
  descripcion        VARCHAR(2000),
  precio_por_noche   NUMERIC(12,2)    NOT NULL,
  capacidad          INTEGER          NOT NULL,
  imagen             VARCHAR(500),                   -- portada
  calificacion       DOUBLE PRECISION,
  resenas            INTEGER,
  habitaciones       INTEGER,
  camas              INTEGER,
  banos              INTEGER,
  destacado          VARCHAR(20),
  activo             BOOLEAN          NOT NULL DEFAULT TRUE,   -- false si esta pausado
  eliminado          BOOLEAN          NOT NULL DEFAULT FALSE,  -- true si el anfitrion lo elimino (no se borra)
  fecha_creacion     TIMESTAMP(6)     NOT NULL,
  fecha_modificacion TIMESTAMP(6),
  id_ciudad          BIGINT           NOT NULL REFERENCES ciudad (id),
  id_tipo_hospedaje  BIGINT           NOT NULL REFERENCES tipo_hospedaje (id),
  id_anfitrion       BIGINT           NOT NULL REFERENCES usuario (id)
);

-- galeria de fotos
CREATE TABLE IF NOT EXISTS hospedaje_imagen (
  id_hospedaje BIGINT  NOT NULL REFERENCES hospedaje (id),
  orden        INTEGER NOT NULL,
  url          VARCHAR(500),
  PRIMARY KEY (id_hospedaje, orden)
);

-- servicios de cada alojamiento (tabla puente sin atributos propios)
-- la clave compuesta impide cargar dos veces el mismo servicio en un alojamiento
CREATE TABLE IF NOT EXISTS servicio_hospedaje (
  id_hospedaje BIGINT NOT NULL REFERENCES hospedaje (id),
  id_servicio  BIGINT NOT NULL REFERENCES servicio (id),
  CONSTRAINT pk_servicio_hospedaje PRIMARY KEY (id_hospedaje, id_servicio)
);

-- dias bloqueados por el anfitrion
CREATE TABLE IF NOT EXISTS bloqueo (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_hospedaje BIGINT       NOT NULL REFERENCES hospedaje (id),
  fecha_desde  DATE         NOT NULL,
  fecha_hasta  DATE         NOT NULL,
  motivo       VARCHAR(255),
  CHECK (fecha_hasta >= fecha_desde)
);

-- fotos subidas desde la compu
CREATE TABLE IF NOT EXISTS imagen (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contenido BYTEA       NOT NULL,
  tipo      VARCHAR(50) NOT NULL
);

-- reservas
CREATE TABLE IF NOT EXISTS reserva (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_hospedaje       BIGINT        NOT NULL REFERENCES hospedaje (id),
  id_usuario         BIGINT        NOT NULL REFERENCES usuario (id),   -- el huésped
  fecha_check_in     DATE          NOT NULL,
  fecha_check_out    DATE          NOT NULL,
  cant_adultos       INTEGER       NOT NULL,
  cant_ninos         INTEGER       NOT NULL,
  cant_bebes         INTEGER       NOT NULL,
  cant_mascotas      INTEGER       NOT NULL,
  importe_total      NUMERIC(12,2) NOT NULL,
  estado             VARCHAR(20)   NOT NULL CHECK (estado IN ('CONFIRMADA', 'CANCELADA')),
  motivo_cancelacion VARCHAR(500),                    -- motivo al cancelar
  cancelada_por      VARCHAR(20),                     -- HUESPED o ANFITRION
  motivo_cambio_fechas VARCHAR(500),                  -- motivo del ultimo cambio de fechas
  fecha_creacion     TIMESTAMP(6)  NOT NULL,
  fecha_modificacion TIMESTAMP(6),
  CHECK (fecha_check_out > fecha_check_in)
);

